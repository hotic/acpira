// Writes the lucide icons the webview imports as Swift data for the iOS app: `pnpm exec tsx scripts/export/ios-icons.ts`.
// The app draws them with the same geometry and stroke rules lucide-react uses (24-unit box, round caps and joins),
// so icons match the webview exactly. test/ios-icons.test.ts fails when the committed file drifts from the imports.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
export const IOS_ICONS_FILE = join(root, 'apps/ios/Packages/AcpiraKit/Sources/AcpiraDesign/LucideIcons.generated.swift');
export const IOS_MARKS_FILE = join(root, 'apps/ios/Packages/AcpiraKit/Sources/AcpiraDesign/Marks.generated.swift');

// Icons the iOS layout needs beyond what the webview imports (iOS-only affordances)
const EXTRA = ['ArrowDown', 'Asterisk', 'Menu', 'Mic', 'Camera'];

type Attrs = Record<string, string | number>;
type IconNode = [string, Attrs][];

/** PascalCase names imported from lucide-react anywhere under packages/ui */
export function importedIcons(): string[] {
  const names = new Set<string>(EXTRA);
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (/\.tsx?$/.test(entry)) {
        for (const m of readFileSync(path, 'utf8').matchAll(/import\s*\{([^}]+)\}\s*from\s*'lucide-react'/g)) {
          for (const part of m[1]!.split(',')) {
            const name = part.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0]!.trim();
            if (name && !/^Lucide|Props$/.test(name)) names.add(name);
          }
        }
      }
    }
  };
  walk(join(root, 'packages/ui'));
  return [...names].sort();
}

/** lucide-react's export map: PascalCase name → icon module file */
function exportMap(): Map<string, string> {
  const require = createRequire(import.meta.url);
  const entry = require.resolve('lucide-react').replace(/cjs\/lucide-react\.js$/, 'esm/lucide-react.mjs');
  const dir = dirname(entry);
  const out = new Map<string, string>();
  for (const m of readFileSync(entry, 'utf8').matchAll(/export \{([^}]+)\} from '(\.\/icons\/[^']+)'/g)) {
    for (const part of m[1]!.split(',')) {
      const alias = part.trim().split(/\s+as\s+/)[1]?.trim();
      if (alias) out.set(alias, join(dir, m[2]!));
    }
  }
  return out;
}

// Swift keywords among lucide names (Import, Repeat …) take backticks
const KEYWORDS = new Set(['import', 'repeat', 'return', 'switch', 'case', 'default', 'in', 'is', 'as', 'func', 'let', 'var', 'class', 'struct', 'enum', 'protocol', 'extension', 'if', 'else', 'for', 'while', 'do', 'try', 'throw', 'catch', 'defer', 'guard', 'where', 'break', 'continue', 'self', 'super', 'init', 'operator', 'public', 'private', 'internal', 'static']);
const camel = (pascal: string) => pascal[0]!.toLowerCase() + pascal.slice(1);
const swiftId = (pascal: string) => KEYWORDS.has(camel(pascal)) ? `\`${camel(pascal)}\`` : camel(pascal);
const num = (v: string | number | undefined) => `${Number(v ?? 0)}`;
const points = (v: string | number | undefined) => `[${String(v ?? '').trim().split(/[\s,]+/).map(num).join(', ')}]`;

/** One lucide node as a Swift `IconElement` literal */
function element([tag, a]: [string, Attrs]): string {
  switch (tag) {
    case 'path': return `.path(${JSON.stringify(a.d)})`;
    case 'circle': return `.circle(cx: ${num(a.cx)}, cy: ${num(a.cy)}, r: ${num(a.r)})`;
    case 'ellipse': return `.ellipse(cx: ${num(a.cx)}, cy: ${num(a.cy)}, rx: ${num(a.rx)}, ry: ${num(a.ry)})`;
    case 'rect': return `.rect(x: ${num(a.x)}, y: ${num(a.y)}, width: ${num(a.width)}, height: ${num(a.height)}, rx: ${num(a.rx ?? a.ry)})`;
    case 'line': return `.line(x1: ${num(a.x1)}, y1: ${num(a.y1)}, x2: ${num(a.x2)}, y2: ${num(a.y2)})`;
    case 'polyline': return `.polyline(${points(a.points)})`;
    case 'polygon': return `.polygon(${points(a.points)})`;
    default: throw new Error(`unsupported lucide element <${tag}>`);
  }
}

export async function iosIconsSwift(): Promise<string> {
  const map = exportMap();
  const cases: string[] = [];
  const bodies: string[] = [];
  for (const name of importedIcons()) {
    const file = map.get(name);
    if (!file) throw new Error(`lucide-react has no icon ${name}`);
    const mod = await import(pathToFileURL(file).href) as { __iconNode: IconNode };
    const id = swiftId(name);
    cases.push(`  case ${id}`);
    bodies.push(`    case .${id}: [${mod.__iconNode.map(element).join(', ')}]`);
  }
  return [
    '// Generated by scripts/export/ios-icons.ts from lucide-react; do not edit.',
    '// The lucide icons the webview imports, as geometry in lucide\'s 24-unit box.',
    '',
    'public enum LucideIcon: String, CaseIterable, Sendable {',
    ...cases,
    '}',
    '',
    'extension LucideIcon {',
    '  /// The icon\'s elements, drawn in order',
    '  public var elements: [IconElement] {',
    '    switch self {',
    ...bodies,
    '    }',
    '  }',
    '}',
    '',
  ].join('\n');
}

/** A `{ key: [...] }` / `{ key: 'value' }` object literal of a source file, read as text (the modules import webview code) */
function literalAfter(source: string, marker: string): string {
  const at = source.indexOf(marker);
  if (at < 0) throw new Error(`missing ${marker}`);
  const start = source.indexOf('{', at);
  return source.slice(start, source.indexOf('\n};', start) + 2);
}

/**
 * The vendor marks (chat/marks.tsx, filled 24-unit paths), their aliases, and the model-name → brand rules
 * (shared/models.ts `BRAND`) as Swift data
 */
export function iosMarksSwift(): string {
  const marks = readFileSync(join(root, 'packages/ui/chat/marks.tsx'), 'utf8');
  const table = literalAfter(marks, 'const MARKS');
  const entries: string[] = [];
  for (const m of table.matchAll(/^\s{2}(\w+): \[([\s\S]*?)^\s{2}\],/gm)) {
    const paths = [...m[2]!.matchAll(/'([^']+)'/g)].map(p => JSON.stringify(p[1]));
    entries.push(`    ${JSON.stringify(m[1])}: [${paths.join(', ')}],`);
  }
  const alias = [...literalAfter(marks, 'const MARK_ALIAS').matchAll(/^\s{2}(\w+): '(\w+)',/gm)]
    .map(m => `    ${JSON.stringify(m[1])}: ${JSON.stringify(m[2])},`);
  const models = readFileSync(join(root, 'packages/shared/models.ts'), 'utf8');
  const brandAt = models.indexOf('const BRAND');
  const brandBlock = models.slice(brandAt, models.indexOf('\n];', brandAt));
  const brands = [...brandBlock.matchAll(/^\s{2}\[\/(.+)\/, '(\w+)'\],/gm)]
    .map(m => `    (#"${m[1]}"#, ${JSON.stringify(m[2])}),`);
  if (!entries.length || !alias.length || !brands.length) throw new Error('marks / brands not found');
  return [
    '// Generated by scripts/export/ios-icons.ts from chat/marks.tsx and shared/models.ts; do not edit.',
    '',
    'public enum VendorMarks {',
    '  /// Filled paths in a 24-unit box, even-odd',
    '  public static let paths: [String: [String]] = [',
    ...entries,
    '  ]',
    '',
    '  /// Keys that borrow another vendor\'s logo',
    '  public static let alias: [String: String] = [',
    ...alias,
    '  ]',
    '',
    '  /// Model family → brand key, first match wins (patterns run on the lowercased name)',
    '  public static let brands: [(pattern: String, brand: String)] = [',
    ...brands,
    '  ]',
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(IOS_ICONS_FILE, await iosIconsSwift());
  writeFileSync(IOS_MARKS_FILE, iosMarksSwift());
}
