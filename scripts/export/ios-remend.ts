// Writes the iOS app's remend conformance cases: `pnpm exec tsx scripts/export/ios-remend.ts`.
// The webview renders a streaming reply through streamdown, which repairs the unfinished tail with remend before
// parsing; the app ports remend to Swift (AcpiraMarkdown/Remend.swift). These cases are the installed remend's own
// output for every prefix of a few streamed documents plus edge cases, and the Swift test replays them.
// test/ios-remend.test.ts fails when the committed cases drift from the installed remend.
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
export const IOS_REMEND_FILE = join(root, 'apps/ios/Packages/AcpiraKit/Tests/AcpiraKitTests/RemendCases.generated.swift');

type Remend = (markdown: string) => string;

/** remend as streamdown loads it (a dependency of streamdown, not of the webview): the sibling of streamdown's real path */
async function loadRemend(): Promise<{ remend: Remend; version: string }> {
  const streamdown = realpathSync(join(root, 'node_modules/streamdown'));
  const dir = join(dirname(streamdown), 'remend');
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as { version: string; main: string };
  const module = await import(pathToFileURL(join(dir, pkg.main)).href) as { default: Remend };
  return { remend: module.default, version: pkg.version };
}

