/** One case: the input as a prefix length of a document or an edge string, and remend's output */
function encode(input: string, output: string): string {
  // Most outputs append to the input: keep only the appended tail
  return output.startsWith(input)
    ? `.append(${JSON.stringify(output.slice(input.length))})`
    : `.full(${JSON.stringify(output)})`;
}

export async function iosRemendSwift(): Promise<string> {
  const { remend, version } = await loadRemend();
  const lines: string[] = [];
  lines.push('// Generated by scripts/export/ios-remend.ts from remend ' + version + '. Do not edit.');
  lines.push('// Each document is streamed one UTF-16 unit at a time; `cases[i]` is remend\'s output for the first i units.');
  lines.push('');
  lines.push('enum RemendOutput { case append(String), full(String) }');
  lines.push('');
  lines.push('enum RemendCases {');
  lines.push(`  static let version = ${JSON.stringify(version)}`);
  lines.push('  static let documents: [(text: String, cases: [RemendOutput])] = [');
  for (const doc of DOCUMENTS) {
    const cases: string[] = [];
    for (let i = 0; i <= doc.length; i++) {
      // Skip a prefix that splits a surrogate pair: no stream ever holds half a character
      const code = doc.charCodeAt(i - 1);
      if (i > 0 && code >= 0xd800 && code <= 0xdbff) { cases.push('.append("")'); continue; }
      const prefix = doc.slice(0, i);
      cases.push(encode(prefix, remend(prefix)));
    }
    lines.push(`    (${JSON.stringify(doc)}, [`);
    for (let i = 0; i < cases.length; i += 8) lines.push(`      ${cases.slice(i, i + 8).join(', ')},`);
    lines.push('    ]),');
  }
  lines.push('  ]');
  lines.push('  static let edges: [(String, String)] = [');
  for (const edge of EDGES) lines.push(`    (${JSON.stringify(edge)}, ${JSON.stringify(remend(edge))}),`);
  lines.push('  ]');
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(IOS_REMEND_FILE, await iosRemendSwift());
  console.log(IOS_REMEND_FILE);
}
