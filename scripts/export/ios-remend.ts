    + '复杂度不变：时间 $O(n)$，空间 $O(1)$；总开销\n\n$$\n\\sum_{i=1}^{n} x_i = X\n$$\n\n'
    + '```mermaid\ngraph LR\n  A[CLI] --> B[parseArgs]\n```\n',
  // Emphasis of every kind, nested and in words
  'Some *italic* and **bold** and ***both*** text, snake_case_name and __dunder__ and _under_ here.\n'
    + 'A ~~struck~~ word, a~b tilde, **bold with _italic_ inside** and *a*b*c* chains.\n'
