// Writes KaTeX's font metrics and copies its fonts for the iOS app's math typesetter: `pnpm exec tsx scripts/export/ios-katex.ts`.
// The webview typesets `$$` math with KaTeX; the app lays out the same TeX subset with KaTeX's own metric tables
// (the TFM data KaTeX ships) and draws the same faces, so a formula lands on the same glyphs at the same places.
// test/ios-katex.test.ts fails when the committed metrics drift from the installed katex.
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const design = join(root, 'apps/ios/Packages/AcpiraKit/Sources/AcpiraDesign');
export const IOS_KATEX_FILE = join(design, 'KaTeXMetrics.generated.swift');
/** The faces the iOS subset uses: upright and bold text, math italic, the two big-operator sizes, AMS symbols */
export const KATEX_FONTS = ['Main-Regular', 'Main-Bold', 'Math-Italic', 'Size1-Regular', 'Size2-Regular', 'AMS-Regular'];

function katexDir(): string {
  return dirname(createRequire(import.meta.url).resolve('katex/package.json'));
}

/** Evaluates one `var name = {…};` object literal from katex.mjs (the tables are not exported) */
function table(source: string, name: string): Record<string, unknown> {
  const start = source.indexOf(`var ${name} = {`);
  if (start < 0) throw new Error(`katex.mjs: ${name} not found`);
  // The literal ends at the first line that closes it at column 0
  const end = source.indexOf('\n};', start);
  const literal = source.slice(source.indexOf('{', start), end + 2);
  return new Function(`return (${literal});`)() as Record<string, unknown>;
}

const num = (n: number) => (Number.isInteger(n) ? String(n) : String(+n.toFixed(5)));

export function iosKatexSwift(): string {
  const dir = katexDir();
  const version = (JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as { version: string }).version;
  const source = readFileSync(join(dir, 'dist/katex.mjs'), 'utf8');
  const metrics = table(source, 'fontMetricsData') as Record<string, Record<string, number[]>>;
  const sigmas = table(source, 'sigmasAndXis') as Record<string, number[]>;
  const fonts = KATEX_FONTS.map(font => {
    const glyphs = metrics[font];
    if (!glyphs) throw new Error(`katex.mjs: no metrics for ${font}`);
    // "codepoint:depth,height,italic,skew,width" joined by ";" — parsed once at run time, a literal this size
    // would cost the Swift type checker far more than the parse
    const packed = Object.entries(glyphs)
      .sort(([a], [b]) => Number(a) - Number(b))
      .map(([code, m]) => `${code}:${m.map(num).join(',')}`)
      .join(';');
    return `    "${font}": "${packed}",`;
  });
  const params = Object.entries(sigmas).map(([k, v]) => `    "${k}": [${v.map(num).join(', ')}],`);
  return [
    `// Generated by scripts/export/ios-katex.ts from katex ${version}; do not edit.`,
    '',
    '/// KaTeX\'s font metric tables: per face, each glyph\'s depth, height, italic correction, skew and width in em,',
    '/// and the TeX font parameters (sigmas and xis) for text, script and scriptscript sizes',
    'public enum KaTeXMetrics {',
    `  public static let version = "${version}"`,
    '',
    '  static let packed: [String: String] = [',
    ...fonts,
    '  ]',
    '',
    '  public static let params: [String: [Double]] = [',
    ...params,
    '  ]',
    '}',
    '',
  ].join('\n');
}

/** Copies the faces next to Inter, under the names the app registers */
export function copyKatexFonts(): void {
  const dir = katexDir();
  for (const font of KATEX_FONTS) {
    copyFileSync(join(dir, 'dist/fonts', `KaTeX_${font}.ttf`), join(design, 'Fonts', `KaTeX_${font}.ttf`));
  }
  copyFileSync(join(dir, 'LICENSE'), join(design, 'Fonts', 'KaTeX-LICENSE.txt'));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(IOS_KATEX_FILE, iosKatexSwift());
  copyKatexFonts();
  console.log(IOS_KATEX_FILE);
}
