#!/usr/bin/env bash
# Builds the HarmonyOS app headless: the iOS app's dictionaries and fixtures compiled in (as the Android build syncs
# them), then hvigor's assembleHap against the public OpenHarmony SDK (docs/dev/harmony.md for the toolchain).
#   OHOS_SDK     the SDK root holding <api>/{ets,js,native,previewer,toolchains} (default ~/Library/OpenHarmony/sdk)
#   DEV_ENGINE   `host:port:token` of a development engine compiled in as the default (the Previewer takes no
#                launch parameters); DEV_PROMPT a first prompt it sends there once connected
#   HVIGOR_HOME  a folder whose node_modules holds @ohos/hvigor and @ohos/hvigor-ohos-plugin (default ~/Library/OpenHarmony/hvigor)
# Usage: apps/harmony/scripts/build.sh [hvigor task …]   (default: assembleHap)
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
ios="$here/../ios/Packages/AcpiraKit/Sources"
sdk="${OHOS_SDK:-$HOME/Library/OpenHarmony/sdk}"
hvigor="${HVIGOR_HOME:-$HOME/Library/OpenHarmony/hvigor}"

# The iOS app's dictionaries and demo fixtures, compiled in as JSON strings (generated, git-ignored): rawfile reads
# come back empty in the Previewer, a module works everywhere
gen="$here/entry/src/main/ets/generated"
mkdir -p "$gen"
python3 - "$ios" "$gen/Assets.generated.ets" <<'PY'
import json, os, sys
ios, out = sys.argv[1], sys.argv[2]
def text(path):
    return json.dumps(json.dumps(json.load(open(path, encoding='utf-8')), ensure_ascii=False, separators=(',', ':')), ensure_ascii=False)
lines = ['// Generated by apps/harmony/scripts/build.sh from the iOS app\'s resources; do not edit', '']
i18n = os.path.join(ios, 'AcpiraUI/Resources/i18n')
lines.append('export const I18N: Map<string, string> = new Map<string, string>([')
lines += [f"  ['{n}', {text(os.path.join(i18n, n + '.json'))}]," for n in ('en', 'zh-CN')]
lines.append(']);')
fx = os.path.join(ios, 'AcpiraFixtures/synthetic')
lines.append('')
lines.append('export const FIXTURES: Map<string, string> = new Map<string, string>([')
lines += [f"  ['{f[:-5]}', {text(os.path.join(fx, f))}]," for f in sorted(os.listdir(fx)) if f.endswith('.json')]
lines.append(']);')
lines.append('')
lines.append(f"export const DEV_ENGINE: string = {json.dumps(os.environ.get('DEV_ENGINE', ''))};")
lines.append(f"export const DEV_PROMPT: string = {json.dumps(os.environ.get('DEV_PROMPT', ''))};")
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
PY

printf 'sdk.dir=%s\n' "$sdk" > "$here/local.properties"
# hvigorfile.ts imports the plugin by name: resolve it from the hvigor install
ln -sfn "$hvigor/node_modules" "$here/node_modules"
cd "$here"
OHOS_BASE_SDK_HOME="$sdk" node "$hvigor/node_modules/@ohos/hvigor/bin/hvigor.js" "${@:-assembleHap}" \
  --mode module -p product=default -p buildMode=debug --no-daemon
