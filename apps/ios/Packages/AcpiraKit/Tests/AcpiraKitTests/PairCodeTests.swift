  /// The rows drawn as a camera would see them, read back with Vision's barcode request
  private static func read(_ rows: [String]) throws -> CIBarcodeDescriptor? {
    let scale = 8, quiet = 4, side = (rows.count + 2 * quiet) * scale
    var pixels = [UInt8](repeating: 255, count: side * side)
    for (y, row) in rows.enumerated() {
      for (x, module) in row.enumerated() where module == "1" {
        for dy in 0..<scale {
          for dx in 0..<scale { pixels[((y + quiet) * scale + dy) * side + (x + quiet) * scale + dx] = 0 }
        }
      }
    }
    guard let provider = CGDataProvider(data: Data(pixels) as CFData),
          let image = CGImage(width: side, height: side, bitsPerComponent: 8, bitsPerPixel: 8, bytesPerRow: side,
                              space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGBitmapInfo(rawValue: 0), provider: provider,
                              decode: nil, shouldInterpolate: false, intent: .defaultIntent) else { return nil }
    let request = VNDetectBarcodesRequest()
    request.symbologies = [.qr]
    try VNImageRequestHandler(cgImage: image).perform([request])
    return request.results?.first?.barcodeDescriptor
  }
